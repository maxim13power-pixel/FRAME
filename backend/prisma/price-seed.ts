/** Легаси-префикс старого демо-справочника */
const LEGACY_PREFIX = '[DEMO] ';

const normName = (value: string): string =>
  value
    .normalize('NFKC')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[«»"'`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

export interface PriceSeedResult {
  catalogId: number;
  categories: number;
  created: number;
  updated: number;
  deactivated: number;
  renamedCategories: number;
}

/**
 * Идемпотентно наполняет системный (образец) справочник рыночными ценами:
 *  • убирает легаси-префикс «[DEMO]» у категорий (дубли сливает);
 *  • создаёт/обновляет позиции по названию + единице + виду;
 *  • деактивирует позиции, которых нет в датасете (DEMO-остатки), — ссылки
 *    в строках смет сохраняются, деньги не меняются.
 */
export async function seedSystemPriceCatalog(
  prisma: PrismaClient,
): Promise<PriceSeedResult> {
  const catalog =
    (await prisma.priceCatalog.findFirst({
      where: { ownerId: null },
      orderBy: { id: 'asc' },
    })) ??
    (await prisma.priceCatalog.create({
      data: { name: 'Демо-справочник', kind: 'SYSTEM' },
    }));
  if (catalog.kind !== 'SYSTEM') {
    await prisma.priceCatalog.update({ where: { id: catalog.id }, data: { kind: 'SYSTEM' } });
  }

  // 1. «[DEMO] X» → «X»
  let renamedCategories = 0;
  const legacy = await prisma.priceCategory.findMany({
    where: { name: { startsWith: LEGACY_PREFIX } },
  });
  for (const category of legacy) {
    const clean = category.name.slice(LEGACY_PREFIX.length).trim();
    if (!clean) continue;
    const existing = await prisma.priceCategory.findFirst({
      where: { name: clean, kind: category.kind },
    });
    if (existing) {
      await prisma.priceItem.updateMany({
        where: { categoryId: category.id },
        data: { categoryId: existing.id },
      });
      await prisma.priceCategory.delete({ where: { id: category.id } });
    } else {
      await prisma.priceCategory.update({
        where: { id: category.id },
        data: { name: clean },
      });
    }
    renamedCategories += 1;
  }

  // 2. Категории и позиции
  const existingItems = await prisma.priceItem.findMany({
    where: { catalogId: catalog.id },
    select: { id: true, name: true, unit: true, kind: true, isActive: true },
  });
  const byKey = new Map(
    existingItems.map((item) => [`${item.kind}|${normName(item.name)}|${item.unit}`, item.id]),
  );
  const keep = new Set<number>();
  let created = 0;
  let updated = 0;
  let categories = 0;

  const groups: [PriceKind, Record<string, Item[]>][] = [
    [PriceKind.WORK, WORK_CATALOG],
    [PriceKind.MATERIAL, MATERIAL_CATALOG],
  ];

  for (const [kind, catalogGroups] of groups) {
    for (const [categoryName, rows] of Object.entries(catalogGroups)) {
      categories += 1;
      const category = await prisma.priceCategory.upsert({
        where: { name_kind: { name: categoryName, kind } },
        update: { sortOrder: categories },
        create: { name: categoryName, kind, sortOrder: categories },
        select: { id: true },
      });

      for (const [name, unit, price] of rows) {
        const key = `${kind}|${normName(name)}|${unit}`;
        const id = byKey.get(key);
        if (id) {
          await prisma.priceItem.update({
            where: { id },
            data: { price, categoryId: category.id, isActive: true },
          });
          keep.add(id);
          updated += 1;
        } else {
          const row = await prisma.priceItem.create({
            data: {
              ownerId: null,
              catalogId: catalog.id,
              name,
              unit,
              price,
              categoryId: category.id,
              kind,
              isActive: true,
            },
            select: { id: true },
          });
          keep.add(row.id);
          byKey.set(key, row.id);
          created += 1;
        }
      }
    }
  }

  // 3. Позиции вне датасета (DEMO-остатки) скрываем, но не удаляем
  const staleIds = existingItems.filter((item) => !keep.has(item.id)).map((item) => item.id);
  let deactivated = 0;
  if (staleIds.length > 0) {
    const result = await prisma.priceItem.updateMany({
      where: { id: { in: staleIds }, isActive: true },
      data: { isActive: false },
    });
    deactivated = result.count;
  }

  return {
    catalogId: catalog.id,
    categories,
    created,
    updated,
    deactivated,
    renamedCategories,
  };
}
